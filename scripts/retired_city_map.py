#!/usr/bin/env python3
"""Generate src/retired-cities.js: where the cards saved with a city feed
the index no longer carries find their stops now.

A feed leaves the city index for good when another feed gives the same
network (build_city_index.RETIRED_FEEDS): Székesfehérvár's menetbrand zip
(`szekesfehervar`, since September 2026) is the Volánbusz town network the
Volán feed gives as `volan-szekesfehervar` since November 2026, with the
same lines and trips, and only the latter has trip ids the realtime feeds
know. A card saved with the retired feed (config.js normalizeCardConfig)
takes the new feed, and its boarding and alighting stops the stop this
table pairs with them. Usage:

    gh release download v1.10.25 -R bator/hungarian-transport -p hungarian-transport.zip
    python3 scripts/retired_city_map.py hungarian-transport.zip --write

INDEX is a city-index.json.gz or a release's hungarian-transport.zip (its
www/city-index.json.gz) that carries both feeds: v1.10.25, the last release
with the menetbrand zip. Run it only against that index: the old ids are
the ones cards saved then.

The pairing: each stop of the retired feed goes to the stop of the new one
with its name (folded: case, accents, punctuation, spaces around "/", and
the new feed's "Székesfehérvár, " town prefix ignored) within NAME_M,
nearest first, else to the nearest stop within NEAR_M (the Volán feed
spells "Tóvárosi lakónegyed" as "lakóngyed"). A stop with neither stays
out of the table, and a card saved with it keeps its id (it matches by
name, as any saved stop the index dropped).
"""

from __future__ import annotations

import argparse
import gzip
import io
import json
import math
import re
import sys
import unicodedata
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "retired-cities.js"
# Retired feed -> (the feed that took its place, the new feed's town prefix).
RETIRED = {"szekesfehervar": ("volan-szekesfehervar", "Székesfehérvár, ")}
NAME_M = 150.0
NEAR_M = 100.0


def load_index(path: Path) -> dict:
    raw = path.read_bytes()
    if zipfile.is_zipfile(io.BytesIO(raw)):
        with zipfile.ZipFile(io.BytesIO(raw)) as zf:
            raw = zf.read("www/city-index.json.gz")
    return json.loads(gzip.decompress(raw))


def fold(name: str, prefix: str = "") -> str:
    s = name.strip()
    if prefix and s.startswith(prefix):
        s = s[len(prefix):]
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    s = re.sub(r"\s*/\s*", "/", s)
    s = re.sub(r"[.,\-]", " ", s)
    return " ".join(s.split())


def metres(a: tuple[float, float], b: tuple[float, float]) -> float:
    dy = (a[0] - b[0]) * 111195.0
    dx = (a[1] - b[1]) * 111195.0 * math.cos(math.radians(a[0]))
    return math.hypot(dx, dy)


def pair(idx: dict, old_op: str, new_op: str, prefix: str) -> dict[str, int]:
    """Old stop id (without the old feed's prefix) -> index of the new stop
    in the index's stop list."""
    ops = {row[0]: i for i, row in enumerate(idx["o"])}
    if old_op not in ops or new_op not in ops:
        raise SystemExit(f"{old_op} and {new_op} must both be in the index")
    g = idx["g"]

    def place(i: int) -> tuple[float, float]:
        return g[2 * i] / 1e5, g[2 * i + 1] / 1e5

    stops = idx["s"]
    new = [i for i, s in enumerate(stops) if s[3] == ops[new_op]]
    out: dict[str, int] = {}
    for i, s in enumerate(stops):
        if s[3] != ops[old_op]:
            continue
        here = place(i)
        near = sorted((metres(here, place(j)), stops[j][0], j) for j in new)
        same = [(m, j) for m, _sid, j in near if m <= NAME_M and fold(stops[j][1], prefix) == fold(s[1])]
        if same:
            j = same[0][1]
        elif near and near[0][0] <= NEAR_M:
            j = near[0][2]
        else:
            print(f"warn {s[0]} ({s[1]}): no stop of {new_op} within {NEAR_M:.0f} m", file=sys.stderr)
            continue
        out[str(s[0]).removeprefix(f"{old_op}:")] = j
    return out


def render(idx: dict, tables: dict[str, tuple[str, dict[str, int]]]) -> str:
    g = idx["g"]
    lines = [
        "/* Generated by scripts/retired_city_map.py; do not edit. */",
        "",
        "/* City feeds the index no longer carries: feed id -> `into`, the feed that",
        "   took its place, `to`, its stops the old ones went to ([id without the",
        "   new feed's prefix, name, lat, lon]), and `from`, old stop id without",
        "   the old feed's prefix -> position in `to`. config.js",
        "   normalizeCardConfig moves a saved card over. */",
        "export const RETIRED_CITIES = {",
    ]
    for old, (into, stops) in sorted(tables.items()):
        used = sorted(set(stops.values()), key=lambda j: str(idx["s"][j][0]))
        at = {j: n for n, j in enumerate(used)}
        lines.append(f"  {json.dumps(old)}: {{")
        lines.append(f"    into: {json.dumps(into)},")
        lines.append("    to: [")
        for j in used:
            row = idx["s"][j]
            sid = str(row[0]).removeprefix(f"{into}:")
            lat, lon = round(g[2 * j] / 1e5, 5), round(g[2 * j + 1] / 1e5, 5)
            lines.append(f"      {json.dumps([sid, str(row[1]), lat, lon], ensure_ascii=False)},")
        lines.append("    ],")
        pairs = [f"{json.dumps(k)}:{at[stops[k]]}" for k in sorted(stops)]
        lines.append("    from: {")
        for n in range(0, len(pairs), 12):
            lines.append("      " + ", ".join(pairs[n:n + 12]) + ",")
        lines.append("    },")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("index", type=Path)
    ap.add_argument("--write", action="store_true", help=f"write {OUT.relative_to(ROOT)}")
    args = ap.parse_args()
    idx = load_index(args.index)
    tables = {}
    for old, (into, prefix) in RETIRED.items():
        stops = pair(idx, old, into, prefix)
        print(f"{old} -> {into}: {len(stops)} stops", file=sys.stderr)
        tables[old] = (into, stops)
    text = render(idx, tables)
    if args.write:
        OUT.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
