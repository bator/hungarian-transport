#!/usr/bin/env python3
"""Generate a city feed's stop id table: the ids an older index gave the
stops a feed renumbered (Szeged's SZKT zip gave every stop a new one).

build_city_index applies the table when it loads the feed (keep_stop_ids,
the feed's "stop_ids" and "stop_aliases" in CITY_FEEDS), so every build
(the release, the weekly Pages build, Home Assistant's local updater) gives
the same stops the same ids, whatever index it replaces. Usage:

    gh release download v1.10.22 -R bator/hungarian-transport -p hungarian-transport.zip
    python3 scripts/stop_id_map.py hungarian-transport.zip szeged.zip --write

OLD_INDEX is a city-index.json.gz or a release's hungarian-transport.zip
(its www/city-index.json.gz), FEED_ZIP the feed's GTFS zip. --write puts
the tables into build_city_index.py between the feed's own markers (one
block per feed, named by its id), and only for a feed whose CITY_FEEDS
entry names them (<FEED>_STOP_IDS as "stop_ids", <FEED>_STOP_ALIASES as
"stop_aliases"): a new feed gets an empty block and those two entries by
hand first. Without --write the tables are printed. Run it again only when
the feed changes its stop ids (the build warns when a stop of the table is
no longer in the feed, or is far from the old stop's place), always
against the index of the last release before the first renumbering
(v1.10.22 for Szeged), so the ids cards saved then stay the ones the index
gives.

The pairing: an old stop of the feed's operator whose id the feed lacks
goes to a stop of the feed that the old index did not name, within ALIAS_M
and served by a trip of the same mode, one to one. Pairs with the same name
(folded: case, accents, spaces and punctuation ignored) go first, then by
distance, nearest first (ties by the old id, then the new); a renamed stop
still pairs with the stop at its place when no stop of its name is near.
An old stop left over (two old stops became one) is an alias of the stop
it would have paired with, at most ALIASES_PER_STOP per stop. One with no
stop of its mode within ALIAS_M (it moved further) is an alias of the
nearest stop of its name and mode within NAME_ALIAS_M, while that stop has
room. The stop id table gives each old id with the old stop's place, which
the build checks the feed's stop against (build_city_index.KEEP_ID_M).
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import json
import sys
import unicodedata
import zipfile
from collections import Counter, defaultdict
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import NamedTuple

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_city_index as bci  # noqa: E402
from gtfs_compact import _meters  # noqa: E402

# The poles of one stop are 20-40 m apart; across a street, its other
# direction usually is too.
ALIAS_M = 50.0
# An old stop with no stop of its mode within ALIAS_M is an alias of a
# stop of its name and mode this near (Szeged's Dózsa utca, 57 m).
NAME_ALIAS_M = 150.0
# A stop is the alias target of at most this many old ids, the best first.
ALIASES_PER_STOP = 4
# The one block of all tables before each feed had its own (until
# November 2026); --write still replaces it with the feed's own block.
LEGACY_BEGIN = "# --- stop id tables: generated by scripts/stop_id_map.py, do not edit by hand ---"
LEGACY_END = "# --- end of the generated stop id tables ---"


def markers(feed_id: str) -> tuple[str, str]:
    """The lines around a feed's generated tables in build_city_index.py."""
    return (f"# --- {feed_id} stop id tables: generated by scripts/stop_id_map.py, do not edit by hand ---",
            f"# --- end of the {feed_id} stop id tables ---")


def table_name(feed_id: str) -> str:
    """The tables' name prefix: SZEGED for SZEGED_STOP_IDS."""
    return feed_id.upper().replace("-", "_")


class Stop(NamedTuple):
    id: str  # without the feed's prefix
    name: str
    num: str
    lat: float
    lon: float
    modes: frozenset[int]


def fold(name: str) -> str:
    """A stop name compared: lower case, without accents, spaces or punctuation."""
    text = unicodedata.normalize("NFKD", name.casefold())
    return "".join(c for c in text if c.isalnum() and not unicodedata.combining(c))


def mode(route_type: object) -> int:
    """A GTFS route_type as its basic mode, the extended codes (700 bus, 800
    trolleybus, 900 tram, 100 rail...) as the basic ones, so SZKT's
    trolleybuses (800) are the old zip's (11)."""
    rt = route_type if isinstance(route_type, int) else 3
    if rt == 800:
        return 11
    for low, basic in ((100, 2), (200, 3), (400, 1), (700, 3), (900, 0), (1000, 4), (1300, 6), (1400, 7)):
        if low <= rt < low + 100:
            return basic
    return rt


def _modes(n: int, trips: Iterable[list]) -> list[set[int]]:
    out: list[set[int]] = [set() for _ in range(n)]
    for t in trips:
        m = mode(t[4] if len(t) > 4 else 3)
        for p in t[2]:
            if isinstance(p, int) and 0 <= p < n:
                out[p].add(m)
    return out


def _stops(rows: list, g: list, trips: list, keep: Iterable[int], prefix: str) -> list[Stop]:
    modes = _modes(len(rows), trips)
    out = []
    for i in keep:
        row = rows[i]
        sid = str(row[0])
        has = len(g) >= 2 * i + 2 and (g[2 * i] or g[2 * i + 1])
        out.append(Stop(sid.removeprefix(prefix), str(row[1]), str(row[2] or ""),
                        g[2 * i] / 1e5 if has else 0.0, g[2 * i + 1] / 1e5 if has else 0.0, frozenset(modes[i])))
    return out


def index_stops(idx: dict, op: str) -> list[Stop]:
    """The stops of operator op in an index with operators."""
    ops = [o[0] for o in idx.get("o") or []]
    rows = idx["s"]
    own = [i for i, row in enumerate(rows) if len(row) > 3 and 0 <= row[3] < len(ops) and ops[row[3]] == op]
    return _stops(rows, idx.get("g") or [], idx.get("t") or [], own, f"{op}:")


def part_stops(parts: list[dict], op: str) -> list[Stop]:
    """The stops of operator op in a feed's parts (build_city_index._load_feed)."""
    return [st for part in parts if part["op_id"] == op
            for st in _stops(part["s"], part.get("g") or [], part.get("t") or [], range(len(part["s"])), f"{op}:")]


Grid = dict[tuple[int, int], list[Stop]]


def _grid(stops: Iterable[Stop]) -> Grid:
    """Stops by cell; a cell is about 550 x 380 m, so the stops within
    NAME_ALIAS_M of a point are in its cell or the eight around it."""
    grid: Grid = defaultdict(list)
    for st in stops:
        if st.lat or st.lon:
            grid[(round(st.lat * 200), round(st.lon * 200))].append(st)
    return grid


def _near(grid: Grid, old: Stop, radius: float = ALIAS_M) -> Iterator[tuple[float, Stop]]:
    """The stops within radius (at most NAME_ALIAS_M) of old that a trip of
    its mode serves (any mode for an old stop without trips), with their
    distance."""
    if not (old.lat or old.lon):
        return
    cy, cx = round(old.lat * 200), round(old.lon * 200)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            for st in grid.get((cy + dy, cx + dx), ()):
                if old.modes and st.modes and not old.modes & st.modes:
                    continue
                d = _meters((old.lat, old.lon), (st.lat, st.lon))
                if d <= radius:
                    yield d, st


def _key(old: Stop, d: float, new: Stop) -> tuple[bool, float, str, str]:
    # Distances to the decimetre: two poles the same distance away are a tie
    # however the floating point falls, and the tie goes by the ids.
    return fold(old.name) != fold(new.name), round(d, 1), old.id, new.id


def pair_stops(old: list[Stop], new: list[Stop]) -> tuple[dict[str, str], dict[str, str]]:
    """(feed stop id -> the old id it keeps, old id -> the feed stop id it is
    an alias of), ids without the feed's prefix; see the module docstring."""
    new_ids = {st.id for st in new}
    old_ids = {st.id for st in old}
    lost = [st for st in old if st.id not in new_ids]
    fresh = _grid(st for st in new if st.id not in old_ids)
    cands = sorted(_key(o, d, n) for o in lost for d, n in _near(fresh, o))
    kept: dict[str, str] = {}
    taken: set[str] = set()
    for _name, _d, oid, nid in cands:
        if oid not in taken and nid not in kept:
            kept[nid] = oid
            taken.add(oid)
    every = _grid(new)
    to: dict[str, list[tuple]] = defaultdict(list)
    for o in lost:
        if o.id not in taken:
            best = min((_key(o, d, n) for d, n in _near(every, o)), default=None)
            if best:
                to[best[3]].append(best)
    aliases: dict[str, str] = {}
    for nid, got in to.items():
        for _name, _d, oid, _nid in sorted(got)[:ALIASES_PER_STOP]:
            aliases[oid] = nid
    # Left over still: the nearest stop of the same name, served by a trip
    # of a mode of the old stop's (an old stop without trips has none).
    room = Counter(aliases.values())
    named = sorted((round(d, 1), o.id, n.id) for o in lost if o.id not in taken and o.id not in aliases
                   for d, n in _near(every, o, NAME_ALIAS_M) if o.modes & n.modes and fold(o.name) == fold(n.name))
    for _d, oid, nid in named:
        if oid not in aliases and room[nid] < ALIASES_PER_STOP:
            aliases[oid] = nid
            room[nid] += 1
    return dict(sorted(kept.items())), dict(sorted(aliases.items()))


def read_old_index(path: Path) -> dict:
    """A city-index.json.gz, or the one in a release's hungarian-transport.zip."""
    raw = path.read_bytes()
    if zipfile.is_zipfile(io.BytesIO(raw)):
        with zipfile.ZipFile(io.BytesIO(raw)) as z:
            raw = z.read("www/city-index.json.gz")
    return json.loads(gzip.decompress(raw))


def tables(old_index: Path, feed_zip: Path, feed_id: str = "szeged") -> tuple[dict, dict, str]:
    """The feed's stop id table (feed stop id -> (old id, the old stop's
    latitude, longitude)), its alias table and the comment naming their
    sources."""
    if not feed_zip.is_file():
        # _load_feed would download it: the tables come from the zip named.
        raise SystemExit(f"{feed_zip}: no such zip")
    feed = next(f for f in bci.CITY_FEEDS if f["id"] == feed_id)
    # The feed as it comes, without the tables of an earlier run.
    bare = {k: v for k, v in feed.items() if k not in ("stop_ids", "stop_aliases")}
    parts = bci._load_feed(feed_zip.parent, bare, feed_zip)
    old = index_stops(read_old_index(old_index), feed_id)
    kept, aliases = pair_stops(old, part_stops(parts, feed_id))
    nums = {st.id: st.num for st in old}
    odd = sorted(oid for oid in kept.values() if nums.get(oid) != oid)
    if odd:
        # keep_stop_ids gives a stop the old id as its number too.
        raise SystemExit(f"old stops whose number is not their id: {odd[:5]}")
    at = {st.id: (st.lat, st.lon) for st in old}
    placed = {nid: (oid, *at[oid]) for nid, oid in kept.items()}
    versions = ",".join(sorted({p.get("feed") or "?" for p in parts}))

    def sha(p: Path) -> str:
        return hashlib.sha256(p.read_bytes()).hexdigest()

    source = (f"# {feed_id}: {old_index.name} (sha256 {sha(old_index)[:16]}) and\n"
              f"# {feed_zip.name} (sha256 {sha(feed_zip)[:16]}, feed {versions}).")
    return placed, aliases, source


def _value(v: str | tuple) -> str:
    """A table value as Python: an id, or (old id, latitude, longitude)."""
    if isinstance(v, str):
        return json.dumps(v)
    return f"({json.dumps(v[0])}, {v[1]:.5f}, {v[2]:.5f})"


def render(feed_id: str, kept: dict, aliases: dict, source: str) -> str:
    """The feed's block of generated tables, between its markers."""
    def table(var: str, rows: dict, what: str) -> str:
        body = "".join(f"    {json.dumps(k)}: {_value(v)},\n" for k, v in rows.items())
        return f"# {what}\n{var} = {{\n{body}}}\n"

    begin, end = markers(feed_id)
    name = table_name(feed_id)
    return (f"{begin}\n{source}\n"
            + table(f"{name}_STOP_IDS", kept, "Feed stop id -> (the old id the index gives it, also as its stop"
                    " number,\n# and the old stop's latitude, longitude).")
            + table(f"{name}_STOP_ALIASES", aliases, "Old id left over -> the feed stop it is an alias of.")
            + f"{end}\n")


def check_feed(feed_id: str) -> None:
    """Refuse --write for a feed whose CITY_FEEDS entry does not name its
    tables: build_city_index would not apply them, or, with the tables of
    another feed replaced, not even import (every builder, Home Assistant's
    local updater too, runs it)."""
    feed = next((f for f in bci.CITY_FEEDS if f["id"] == feed_id), None)
    if feed is None:
        raise SystemExit(f"{feed_id}: no such feed in CITY_FEEDS")
    name = table_name(feed_id)
    for key, var in (("stop_ids", f"{name}_STOP_IDS"), ("stop_aliases", f"{name}_STOP_ALIASES")):
        if var not in vars(bci) or feed.get(key) is not vars(bci)[var]:
            raise SystemExit(f"{feed_id}: its CITY_FEEDS entry does not name {var} as {key!r}; add an empty"
                             f" block between {markers(feed_id)[0]!r} and its end line defining {name}_STOP_IDS"
                             f" and {name}_STOP_ALIASES, name them in the entry, then run --write again")


def write_tables(text: str, target: Path, feed_id: str) -> None:
    """Replace the feed's block in target with text, or the one block of
    the scripts before per-feed blocks when it holds this feed's tables."""
    src = target.read_text(encoding="utf-8")
    begin, end = markers(feed_id)
    start, stop = src.find(begin), src.find(end)
    if start < 0 and stop < 0:
        old_start, old_stop = src.find(LEGACY_BEGIN), src.find(LEGACY_END)
        if 0 <= old_start < old_stop and f"\n{table_name(feed_id)}_STOP_IDS = " in src[old_start:old_stop]:
            start, stop, end = old_start, old_stop, LEGACY_END
    if start < 0 or stop < start:
        raise SystemExit(f"{target.name}: no generated {feed_id} stop id tables to replace")
    target.write_text(src[:start] + text + src[stop + len(end) + 1:], encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("old_index", type=Path)
    ap.add_argument("feed_zip", type=Path)
    ap.add_argument("--feed", default="szeged")
    ap.add_argument("--write", action="store_true", help="replace the tables in build_city_index.py")
    args = ap.parse_args(argv)
    if args.write:
        check_feed(args.feed)
    kept, aliases, source = tables(args.old_index, args.feed_zip, args.feed)
    text = render(args.feed, kept, aliases, source)
    print(f"{args.feed}: {len(kept)} stops keep an old id, {len(aliases)} aliases", file=sys.stderr)
    if args.write:
        write_tables(text, Path(bci.__file__), args.feed)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
